// Most tunnel threads one tun interface can have. Each tunnel thread opens its own queue on the
// multi-queue tun device, and the kernel allows at most 256 queues per device (MAX_TAP_QUEUES in
// drivers/net/tun.c; attaching another fails with E2BIG). Each gwi- device also needs at least one
// queue for its writers (see gwiWriterCount), which leaves at most 255 for reader threads.
#define TUN_MAX_THREADS 255

// gwi- writers: one writer fd (tun queue) per this many UDP receiver threads (and at least one per network
// receive queue; see gwiWritersWanted). Each writer's queue is
// detached (TUNSETQUEUE IFF_DETACH_QUEUE): writes through a detached queue are still delivered, but skip
// the kernel's per-packet flow-table update (tun_flow_update), which takes a per-device spinlock whenever
// a flow isn't in its 4096-entry table. On many-core hosts that spinlock, and then a single writer fd's
// accounting, were the limit. One writer per 8 threads measured the same as one per thread.
#define GWI_WRITER_SHARE 8
// gwi- writers an endpoint wants: one per GWI_WRITER_SHARE UDP threads, and at least one per network receive
// queue (rxQueues: the most on any interface gwlbtun receives on).
inline size_t gwiWritersWanted(size_t udpThreads, size_t rxQueues)
{
    return std::max<size_t>({ (udpThreads + GWI_WRITER_SHARE - 1) / GWI_WRITER_SHARE, rxQueues, 1 });
}
// gwi- writers an endpoint opens. A tun device has at most 256 queues (attached or detached), shared by the
// writers and the tunnel (reader) threads, so the writers get what the readers leave, and at least one.
inline size_t gwiWriterCount(size_t udpThreads, size_t rxQueues, size_t tunThreads)
{
    return std::max<size_t>(1, std::min(gwiWritersWanted(udpThreads, rxQueues), 256 - std::min<size_t>(255, tunThreads)));
}
