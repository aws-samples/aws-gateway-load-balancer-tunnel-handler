// Owns one file descriptor and closes it when destroyed. Movable, not copyable.
class UniqueFd {
public:
    UniqueFd() noexcept = default;
    explicit UniqueFd(int fd) noexcept : fd(fd) {}
    ~UniqueFd() { reset(); }
    UniqueFd(UniqueFd &&o) noexcept : fd(o.release()) {}
    UniqueFd &operator=(UniqueFd &&o) noexcept { if(this != &o) reset(o.release()); return *this; }
    UniqueFd(const UniqueFd &) = delete;
    UniqueFd &operator=(const UniqueFd &) = delete;

    int get() const noexcept { return fd; }
    explicit operator bool() const noexcept { return fd >= 0; }
    int release() noexcept { int f = fd; fd = -1; return f; }
    void reset(int newFd = -1) noexcept { if(fd >= 0) ::close(fd); fd = newFd; }

private:
    int fd = -1;
};

// A one-shot wake-up for threads blocked in poll(): an eventfd that nothing ever reads, so once signal()
// has been called it stays readable, and every poll() on it returns, whether it was already waiting or
// starts later. One signal() therefore wakes any number of threads. signal() is async-signal-safe.
// The constructor throws std::system_error if the eventfd can't be created.
class EventFd {
public:
    EventFd();
    void signal() const noexcept;
    // Wait up to ms milliseconds (-1: no limit) for signal(). Returns true once it has been called.
    bool waitFor(int ms) const noexcept;
    bool isSignalled() const noexcept { return waitFor(0); }
    int get() const noexcept { return fd.get(); }

private:
    UniqueFd fd;
};

