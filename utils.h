// Coarse monotonic clock: whole seconds since process start, updated twice a
// second by its own thread (CoarseClock in main.cpp). Lets hot paths stamp/compare
// times without a per-packet clock syscall. Reads real kernel time (not a tick
// counter) so it stays accurate if the thread wakes irregularly, and uses a boottime-style source
// so elapsed time keeps advancing across a system suspend.
extern std::atomic<uint32_t> g_coarseSec;
void initCoarseClock();      // Record the start reference; call once at startup.
void updateCoarseClock();    // Refresh g_coarseSec from kernel time; call ~1/s.
inline uint32_t coarseTime() { return g_coarseSec.load(std::memory_order_relaxed); }

// INVARIANT: hashFlow MUST return the same hash for both directions of a flow
// (src/dst and port swap), and PacketHeaderV4/V6::operator== relies on that
// symmetry (it treats a flow and its reverse as equal). The flow cache learns a flow
// from packets arriving from GWLB and looks it up with the header of the reply going
// the other way, and keeps one GENEVE header per flow for both directions, so the
// invariant is permanent. Do not introduce a direction-dependent hash here: every
// operation below (XOR, +) is commutative in src/dst and in the two ports.
inline size_t hashFlowPorts(size_t hash, uint16_t srcpt, uint16_t dstpt)
{
    const uint32_t portMix = srcpt ^ dstpt;
    return hash ^ ((portMix << 16) | (uint32_t)(srcpt + dstpt));
}
// IPv4 flow hash (addresses in host byte order).
inline size_t hashFlow(uint8_t prot, uint32_t src, uint32_t dst, uint16_t srcpt, uint16_t dstpt)
{
    const uint32_t ipMix = src ^ dst;
    size_t hash = prot;
    hash ^= (ipMix << 7) | (ipMix >> 25);           // rotate left 7
    hash ^= (uint32_t)((src + dst) * 0x9e3779b1u);  // golden ratio mixing
    return hashFlowPorts(hash, srcpt, dstpt);
}
// IPv6 flow hash.
inline size_t hashFlow(uint8_t prot, const struct in6_addr &src, const struct in6_addr &dst, uint16_t srcpt, uint16_t dstpt)
{
    uint32_t s[4], d[4];
    std::memcpy(s, &src, sizeof s);
    std::memcpy(d, &dst, sizeof d);
    const uint32_t ipMix = s[0] ^ s[1] ^ s[2] ^ s[3] ^ d[0] ^ d[1] ^ d[2] ^ d[3];
    size_t hash = prot;
    hash ^= (ipMix << 13) | (ipMix >> 19);          // rotate left 13
    hash ^= (uint32_t)(ipMix * 0x9e3779b1u);
    return hashFlowPorts(hash, srcpt, dstpt);
}

